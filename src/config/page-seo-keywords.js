/** @param {'home' | 'doctores'} page @param {string} lang */
export function buildPageKeywords(page, lang) {
    const code = lang in HOME_BASE ? lang : "es";
    const base = page === "home" ? HOME_BASE[code] : DOCTORES_BASE[code];
    const extra = PAGE_SEO_KEYWORDS[page]?.[code] ?? PAGE_SEO_KEYWORDS[page]?.es ?? [];
    return [...base, ...extra].join(", ");
}
